/// Servicio de inicialización de datos base para NB Selfcare.
///
/// Si la base de datos está vacía, puebla automáticamente:
/// 1. Catálogo de alimentos reales en español con datos nutricionales y de electrolitos (USDA).
/// 2. Estado inicial de la mascota virtual ('Nibi') con 50 monedas y 1 escudo de racha.
abstract final class DatabaseSeeder {
  static Future<void> seedIfEmpty(AppDatabase db) async {
    // 1. Verificar si existen alimentos
    final foodCountQuery = db.selectOnly(db.foodItems)..addColumns([db.foodItems.id.count()]);
    final int foodCount = await foodCountQuery.map((row) => row.read(db.foodItems.id.count()) ?? 0).getSingle();

    if (foodCount == 0) {
      await _seedFoodItems(db);
    }

    // 2. Verificar estado de la mascota
    final petCountQuery = db.selectOnly(db.petStatus)..addColumns([db.petStatus.id.count()]);
    final int petCount = await petCountQuery.map((row) => row.read(db.petStatus.id.count()) ?? 0).getSingle();

    if (petCount == 0) {
      await db.into(db.petStatus).insert(
        const PetStatusCompanion(
          petName: Value('Nibi'),
          coinsBalance: Value(50),
          currentStreakDays: Value(0),
          highestStreakDays: Value(0),
          streakShieldsAvailable: Value(1),
          equippedBackgroundId: Value('bg_default_room'),
          unlockedItemsJson: Value('["bg_default_room"]'),
        ),
      );
    }
  }

